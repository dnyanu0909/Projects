const verseMap = new Map(verses.map((v) => [verseKey(v.chapter, v.verse), v]));

export const getVerse = (chapter: number, verse: number) =>
  verseMap.get(verseKey(chapter, verse));

export const getVersesForChapter = (chapter: number) =>
  verses.filter((v) => v.chapter === chapter);

export const getVersesForStruggle = (slug: string) =>
  verses.filter((v) => v.struggles.includes(slug as never));

export const getDailyVerse = (): Verse => {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const day = Math.floor((now.getTime() - start.getTime()) / 86400000);
  return verses[day % verses.length];
};
