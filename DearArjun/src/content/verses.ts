// ─── Helpers ─────────────────────────────────────────────────────────────────

export const getVerseById = (id: string): Verse | undefined => VERSES[id];

export const getVersesByIds = (ids: string[]): Verse[] =>
  ids.map((id) => VERSES[id]).filter((v): v is Verse => v !== undefined);
export const verses: Verse[] = Object.values(VERSES).sort(
  (a, b) => a.chapterNumber - b.chapterNumber || a.verseNumber - b.verseNumber,
);

export const getVerse = (chapter: number, verse: number): Verse | undefined =>
  VERSES[verseKey(chapter, verse)];

export const getVersesForChapter = (chapter: number): Verse[] =>
  verses.filter((v) => v.chapterNumber === chapter);

export const getVersesForStruggle = (slug: string): Verse[] =>
  verses.filter((v) => (v.struggles as string[]).includes(slug));

export const getDailyVerse = (): Verse => {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const day = Math.floor((now.getTime() - start.getTime()) / 86400000);
  return verses[day % verses.length];
};
